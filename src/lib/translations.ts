export const TRANSLATIONS: Record<LangCode, Dict> = {
  en, tr, es, pt, fr, de, it, ru, ja, ko, zh, hi, ar, bn, ur,
};

export function translate(lang: LangCode, key: string, vars?: Record<string, string | number>): string {
  let s = TRANSLATIONS[lang]?.[key] ?? TRANSLATIONS.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

export function isLangCode(v: string | null | undefined): v is LangCode {
  return !!v && LANGS.some((l) => l.code === v);
}
